"""Isolated frozen-Actor TD versus TD+local paired-return supervision.

This small finite-6s-return experiment tests a mechanism, not acceptance for
large-scale training. Fit labels and internal holdout are disjoint train maps;
neither validation nor test maps contribute gradients.
"""
import argparse
import copy
import json
from pathlib import Path

import numpy as np
import torch

from scripts.audit_ego20x10_value import (
    DEFAULT as BASELINE, SOURCE, LOGS, load, learner, rng_restore,
    env_for, reconstruct_state, preprocess_state, rows, fingerprint, write,
)
from scripts.evaluate_ego20x10_d3 import finite_rollout
from scripts.run_ego20x10_d3 import ScheduledBuffer, save_checkpoint
from scripts.ego20x10_contract_variants import critic_calibration_step
from scripts.audit_full_critic_frozen import project, action_gradient
from scripts.run_full_critic_frozen import production_hashes
from scripts.run_full_ft_v2 import sha

ROOT = Path('analysis_outputs/full_ego20x10_local_calibration_pilot_v1')
FIT_MAPS = {46, 9, 24, 85, 69}
WEIGHT = 100.
LOCAL_STEP = .15
RETURN_TIE = .005


def prepare(root):
    root.mkdir(parents=True, exist_ok=False)
    protected = production_hashes()
    protected.update({str(p): sha(p) for p in SOURCE.iterdir() if p.is_file()})
    protected.update({str(p): sha(p) for p in BASELINE.rglob('*') if p.is_file()})
    write(root/'protected_inputs.json', protected)
    write(root/'protocol.json', {
        'kind': 'Small frozen-Actor mechanism pilot; no online learning or formal mode changes',
        'source': 'Original16m full scratch seed43 complete5k learner snapshot',
        'data': 'A actual Replay prefixes5001..5200, identical recorded main/success sampling and target noise',
        'new_critic_updates': 200, 'new_actor_updates': 0,
        'weight': WEIGHT, 'loss': 'L_TD + 100 * (MSE(deltaQ1,deltaG)+MSE(deltaQ2,deltaG))',
        'paired_actions': 'Original5k deterministic Actor plus/minus0.15 on each normalized axis, projected; only first action changed',
        'paired_return': 'Exact Full finite6s G, reward scale0.1, gamma0.99, common frozen5k Actor suffix, truncate on real termination',
        'fit_map_indices': sorted(FIT_MAPS), 'internal_holdout_map_indices': [3, 16, 29],
        'states': 'Existing twelve real Replay representatives, map-disjoint split declared before pair generation',
        'local_direction_check': 'Fresh Full branches along the final critic Q1 gradient, only on internal holdout states',
        'limits': ['Finite6s returns are not infinite-horizon smoothed TD3 values.',
                   'Small internal train-map holdout cannot establish validation generalization.',
                   'Shared data were generated by the original A behavior, including its collapse.',
                   'One predeclared weight, no validation-driven parameter search; does not select a new task contract.'],
        'test_episodes': 0, 'validation_training_samples': 0,
    })


def labels(root):
    six, five = load(6000), load(5000)
    replay = six['replay']['arrays']
    resets = rows(LOGS/'p0_audit/resets.jsonl')
    cases = json.loads(Path('analysis_outputs/full_scratch_ego20x10_d3_critic_lead_200/paired_values.json').read_text())
    actor = learner(five).actor
    env = env_for(six, training_course=False, pool_split='train')
    records = []
    try:
        for case in cases:
            index = case['index']
            obs, reset, error = reconstruct_state(env, index, replay, resets)
            assert error == 0
            initial = obs.copy()
            state = preprocess_state(obs)
            with torch.no_grad():
                action = actor(torch.as_tensor(state).reshape(1, -1))[0].numpy()
            for axis in range(3):
                candidates = [project(action+sign*LOCAL_STEP*np.eye(3)[axis]) for sign in (1, -1)]
                physical = []
                for first in candidates:
                    restored, _, error = reconstruct_state(env, index, replay, resets)
                    np.testing.assert_array_equal(restored, initial)
                    assert error == 0
                    physical.append(finite_rollout(env, restored, first, actor))
                delta = physical[0]['returns']['90']['discounted_scaled_return']-physical[1]['returns']['90']['discounted_scaled_return']
                records.append({'index': index, 'map_index': reset['map_pool_index'], 'groups': case['groups'],
                    'split': 'fit' if reset['map_pool_index'] in FIT_MAPS else 'internal_holdout',
                    'state': state.tolist(), 'axis': axis, 'plus': candidates[0].tolist(), 'minus': candidates[1].tolist(),
                    'delta_G': delta, 'physical_plus': physical[0], 'physical_minus': physical[1],
                    'state_reconstruction_error': error})
            write(root/'paired_labels.json', records)
            print(f'[Local labels] replay={index} map={reset["map_pool_index"]} fit={reset["map_pool_index"] in FIT_MAPS}', flush=True)
    finally:
        env.close()


def pair_tensors(records, split):
    selected = [r for r in records if r['split'] == split]
    assert selected
    return tuple(torch.tensor([r[key] for r in selected], dtype=torch.float32)
                 for key in ('state', 'plus', 'minus'))+(torch.tensor([[r['delta_G']] for r in selected], dtype=torch.float32),)


def pair_scores(agent, records, split):
    state, plus, minus, target = pair_tensors(records, split)
    with torch.no_grad():
        qplus = agent.critic(state, plus)
        qminus = agent.critic(state, minus)
    valid = target[:, 0].abs() > RETURN_TIE
    scores = {}
    for j in range(2):
        difference = (qplus[j]-qminus[j])[:, 0]
        correct = (difference*target[:, 0] > 0) & (difference.abs() > 1e-6)
        scores[f'q{j+1}'] = {'pairs': len(target), 'distinguishable_pairs': int(valid.sum()),
            'agreement': float(correct[valid].float().mean()) if valid.any() else None,
            'delta_return_rmse': float(torch.mean((difference-target[:, 0])**2).sqrt())}
    return scores


def train(root):
    five, six = load(5000), load(6000)
    records = json.loads((root/'paired_labels.json').read_text())
    fit = pair_tensors(records, 'fit')
    assert {r['map_index'] for r in records if r['split']=='fit'}.isdisjoint(
        {r['map_index'] for r in records if r['split']=='internal_holdout'})
    schedule = np.load(BASELINE/'batch_schedule.npz')
    results, checkpoints = {}, {}
    for name, weight in (('td_only', 0.), ('td_local', WEIGHT)):
        agent = learner(copy.deepcopy(five))
        agent.actor_frozen = True
        initial_actor, initial_target = fingerprint(agent.actor), fingerprint(agent.actor_target)
        (root/name/'checkpoints').mkdir(parents=True)
        history = [{'step': 5000, **{s: pair_scores(agent, records, s) for s in ('fit', 'internal_holdout')}}]
        rng_restore(five)
        updates = []
        for n, step in enumerate(schedule['steps'][:200]):
            main = ScheduledBuffer(six['replay']['arrays'])
            main.set_batch(schedule['main_indices'][n], int(step))
            success = ScheduledBuffer(five['success']['strata'][10]['arrays'])
            success.set_batch(schedule['success_indices'][n], 297)
            batch = tuple(torch.cat((a, b)) for a, b in zip(main.sample(205), success.sample(51)))
            generator = torch.Generator().set_state(torch.get_rng_state())
            noise = (torch.randn((256, 3), generator=generator)*agent.policy_noise).clamp(-agent.noise_clip, agent.noise_clip)
            np.testing.assert_array_equal(noise.numpy(), schedule['target_noise'][n])
            info = critic_calibration_step(agent, batch, fit if weight else None, weight)
            torch.testing.assert_close(torch.get_rng_state(), generator.get_state(), atol=0, rtol=0)
            updates.append({'step': int(step), **info})
            if (n+1) in (20, 50, 100, 200):
                score = {'step': int(step), **{s: pair_scores(agent, records, s) for s in ('fit', 'internal_holdout')}}
                history.append(score)
                save_checkpoint(agent, root/name, int(step), 0, five)
                print(f'[Local calibration] {name} updates={n+1} fit={score["fit"]["q1"]["agreement"]} holdout={score["internal_holdout"]["q1"]["agreement"]}', flush=True)
        assert fingerprint(agent.actor)==initial_actor and fingerprint(agent.actor_target)==initial_target
        assert not agent.actor_optimizer.state
        write(root/name/'updates.json', updates)
        write(root/name/'pair_scores.json', history)
        results[name] = history
        checkpoints[name] = agent
    # Original D3 B5200 had exactly the same 200 frozen TD-only updates.
    expected = torch.load(Path('analysis_outputs/full_scratch_ego20x10_d3_critic_lead_200/B/checkpoints/step5200.pt'), map_location='cpu', weights_only=False)
    comparisons = {n: all(torch.equal(v, getattr(checkpoints['td_only'], n).state_dict()[k])
        for k, v in expected['networks'][n].items()) for n in ('actor', 'actor_target', 'critic', 'critic_target')}
    assert all(comparisons.values()), comparisons
    write(root/'training_proof.json', {'td_only_exact_B5200': comparisons, 'actor_updates': 0,
        'critic_updates_per_branch': 200, 'optimizer_steps_per_branch': 200,
        'same_main_success_indices_and_target_noise': True, 'fit_and_holdout_maps_disjoint': True,
        'fit_maps': sorted(FIT_MAPS), 'validation_used_in_training': False})
    write(root/'pair_scores.json', results)
    return checkpoints


def gradients(root, agents):
    records = json.loads((root/'paired_labels.json').read_text())
    cases = {r['index']: r for r in records if r['split']=='internal_holdout'}
    six = load(6000)
    replay = six['replay']['arrays']
    resets = rows(LOGS/'p0_audit/resets.jsonl')
    env = env_for(six, training_course=False, pool_split='train')
    output = []
    try:
        for index, case in cases.items():
            for label, agent in agents.items():
                obs, _, error = reconstruct_state(env, index, replay, resets)
                assert error == 0
                state = preprocess_state(obs)
                source = project(agent.select_action(state))
                grad = action_gradient(agent, state, source)
                direction = grad/max(float(np.linalg.norm(grad)), 1e-12)
                candidates = [project(source+sign*LOCAL_STEP*direction) for sign in (1, -1)]
                branches = []
                for action in candidates:
                    restored, _, error = reconstruct_state(env, index, replay, resets)
                    assert error == 0
                    branches.append(finite_rollout(env, restored, action, agent.actor))
                delta = branches[0]['returns']['90']['discounted_scaled_return']-branches[1]['returns']['90']['discounted_scaled_return']
                output.append({'index': index, 'map_index': case['map_index'], 'branch': label, 'gradient': grad.tolist(),
                    'G_plus_minus_G_minus': delta, 'distinguishable': bool(abs(delta)>RETURN_TIE),
                    'direction_agrees': bool(delta>RETURN_TIE), 'plus': branches[0], 'minus': branches[1]})
                write(root/'holdout_gradient_branches.json', output)
    finally:
        env.close()


def finish(root):
    guarded = json.loads((root/'protected_inputs.json').read_text())
    changed = [p for p, digest in guarded.items() if sha(Path(p))!=digest]
    write(root/'protection_result.json', {'unchanged': not changed, 'changed': changed,
        'checked_files': len(guarded), 'test_episodes': 0, 'validation_training_samples': 0})
    if changed:
        raise RuntimeError(changed)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT)
    args = parser.parse_args()
    torch.set_num_threads(2)
    prepare(args.output)
    labels(args.output)
    agents = train(args.output)
    gradients(args.output, agents)
    finish(args.output)


if __name__ == '__main__':
    main()
